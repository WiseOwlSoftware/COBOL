namespace WiseOwl.Cobol.Tests.Unit;

/// <summary>
/// ⛔ THE FACTS THE DOCUMENTS STATE ABOUT THE COMPILER ARE ONE FILE, HELD EQUAL TO THE COMPILER HERE (kb/Work PB4453).
/// No compiler test opens a Markdown file (owner 2026-11-02: "There is no compelling reason a compiler change needs to
/// read an markdown note"), so a document that states a number, a name list or an option set the compiler holds is
/// checked by <c>scripts/doc_audits.py</c> against <c>tests/doc-facts/compiler-facts.json</c>, and THIS class is the other
/// half: the file equals what the compiler reports, so a compiler change that moves a documented fact turns this test red
/// until the file is regenerated, and the regeneration (a code-path change) is what makes the audit judge the document.
/// <para>
/// Regenerate: <c>WISEOWL_COBOL_WRITE_DOC_FACTS=1 dotnet test --filter DocumentedFactsDriftTests</c>. Each fact below says
/// which document states it; the file is sorted and deterministic, so a diff shows exactly the fact that moved.
/// </para>
/// </summary>
public sealed class DocumentedFactsDriftTests
{
    private static readonly JsonSerializerOptions Options = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    private static JsonArray Strings(IEnumerable<string> values) =>
        new([.. values.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).Select(v => (JsonNode?)JsonValue.Create(v))]);

    private static JsonObject Facts()
    {
        var l3 = ExceptionCatalog.Level3Rows;
        var members = typeof(CobolSort).GetMethods(BindingFlags.Public | BindingFlags.Static)
            .Select(m => new JsonObject
            {
                ["name"] = m.Name,
                ["parameters"] = new JsonArray([.. m.GetParameters().Select(p => (JsonNode?)new JsonObject
                {
                    ["name"] = p.Name,
                    ["optional"] = p.IsOptional,
                })]),
            })
            .OrderBy(o => o.ToJsonString(), StringComparer.Ordinal)
            .ToList();
        var (command, _) = Program.BuildParser();
        var options = command.Options.SelectMany(o => o.Aliases.Append(o.Name))
            .Where(n => n.StartsWith("--", StringComparison.Ordinal));
        var statuses = Enum.GetValues<CompilerDriver.Outcome>().Select(o => Program.ExitCode(o)).Append(Program.LibraryRunExitCode)
            .Distinct().Order();
        var codes = DiagnosticCatalog.All.Select(d => d.Code)
            .Concat(typeof(Frontend.Diagnostics.DiagnosticDescriptors).GetFields()
                .Where(f => f.FieldType == typeof(Frontend.Diagnostics.DiagnosticDescriptor))
                .Select(f => ((Frontend.Diagnostics.DiagnosticDescriptor)f.GetValue(null)!).Code))
            .Concat(ConstructCodes());
        return new JsonObject
        {
            ["comment"] = "GENERATED by DocumentedFactsDriftTests from the compiler (WISEOWL_COBOL_WRITE_DOC_FACTS=1); read by "
                + "scripts/doc_audits.py to hold the Markdown to the compiler without a compiler test opening a Markdown file "
                + "(kb/Work PB4453). Do not edit.",
            // docs/CONFORMANCE.md §7 DOC-A.1-62 and DOC-A.1-93.
            ["dynamicLengthMaximum"] = CobolDynString.MaxLength,
            ["returnedValueMaximum"] = CobolIntrinsics.ReturnedValueMaximum,
            // DOC-A.1-99 and DOC-A.1-100.
            ["ecImplementorLevel2Names"] = Strings(l3.Where(i => i.Fatality == EcFatality.Imp).Select(i => i.Name)),
            ["ecImpSuffixNames"] = Strings(l3.Where(i => i.Name.StartsWith("EC-IMP-", StringComparison.Ordinal)).Select(i => i.Name)),
            // DOC-A.1-92.
            ["functionDeviceFormRowNames"] = Strings(new[] { FunctionDeviceForm.Argument, FunctionDeviceForm.FixedDigits, FunctionDeviceForm.Literal }
                .SelectMany(FunctionDeviceFormDriftTests.RowsDeclaring)),
            // docs/VERSION_CHANGE_REFERENCE.md's <!-- behavior:id --> anchors.
            ["dialectBehaviors"] = new JsonArray([.. DialectBehaviors.All.ToArray().OrderBy(r => r.Id, StringComparer.Ordinal)
                .Select(r => (JsonNode?)new JsonObject { ["id"] = r.Id, ["vcrRow"] = r.VcrRow })]),
            // docs/CONFORMANCE.md §3.2.
            ["nonstandardExtensionIds"] = Strings(NonstandardExtensionRegister.Entries.Select(e => e.Id)),
            // DOC-A.1-189, DOC-A.1-190 and DOC-A.1-191.
            ["implementorNameElements"] = new JsonObject
            {
                ["Device"] = Strings(ImplementorNamesDriftTests.Elements(SystemNameKind.Device)),
                ["Feature"] = Strings(ImplementorNamesDriftTests.Elements(SystemNameKind.Feature)),
                ["Switch"] = Strings(ImplementorNamesDriftTests.Elements(SystemNameKind.Switch)),
            },
            // docs/manual: the diagnostic codes a page may name, the command line's options and exit statuses.
            ["allocatedDiagnosticCodes"] = Strings(codes),
            ["cliOptions"] = Strings(options),
            ["cliExitStatuses"] = new JsonArray([.. statuses.Select(s => (JsonNode?)JsonValue.Create(s))]),
            // The design docs' CobolSort calls and the binder design's OperandPositions table.
            ["cobolSortMembers"] = new JsonArray([.. members]),
            ["operandPositionRows"] = Strings(typeof(OperandPositions).GetFields(BindingFlags.Public | BindingFlags.Static)
                .Where(f => f.FieldType == typeof(OperandPosition)).Select(f => f.Name)),
        };
    }

    private static IEnumerable<string> ConstructCodes()
    {
        using var doc = JsonDocument.Parse(File.ReadAllText(TestRepo.VersionMatrix("constructs.json")));
        return [.. doc.RootElement.GetProperty("constructs").EnumerateArray().Select(c => c.GetProperty("diagnosticCode").GetString()!)];
    }

    private static string FactsPath => TestRepo.At("tests", "doc-facts", "compiler-facts.json");

    [Fact]
    public void TheFactsFile_IsWhatTheCompilerReports()
    {
        string rendered = Facts().ToJsonString(Options).Replace("\r\n", "\n") + "\n";
        if (Environment.GetEnvironmentVariable("WISEOWL_COBOL_WRITE_DOC_FACTS") == "1")
        {
            File.WriteAllText(FactsPath, rendered, new System.Text.UTF8Encoding(false));
            return;
        }

        string committed = File.Exists(FactsPath) ? File.ReadAllText(FactsPath).Replace("\r\n", "\n") : "";
        Assert.True(committed == rendered,
            "tests/doc-facts/compiler-facts.json is out of step with the compiler: a documented fact moved. Regenerate it "
            + "(WISEOWL_COBOL_WRITE_DOC_FACTS=1 dotnet test --filter DocumentedFactsDriftTests), then run "
            + "`python scripts/doc_audits.py --check` and fix the document that states the fact.");
    }
}
