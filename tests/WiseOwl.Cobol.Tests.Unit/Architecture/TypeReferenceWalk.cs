using System.Collections.Immutable;
using System.Reflection;
using System.Reflection.Emit;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Reflection.PortableExecutable;

namespace WiseOwl.Cobol.Tests.Unit.Architecture;

/// <summary>One type definition the walk read: its full metadata name (<c>Ns.Outer+Nested`1</c>, the census's id),
/// the outermost type it folds into, that type's namespace, and whether it is GENERATED by the census's rule.</summary>
internal sealed record WalkedType(string Name, string Outermost, string Namespace, bool Generated);

/// <summary>A dependency between two OUTERMOST product types: <paramref name="From"/> (authored) names
/// <paramref name="To"/>.</summary>
internal readonly record struct TypePair(string From, string To);

/// <summary>
/// THE ARCHITECTURE WALK (kb/Work PB2417; docs/rearchitecture/DESIGN-architecture-review.md §8.1 "The drift test"): a
/// metadata walk over the BUILT product assemblies, never a source scan and never an MSBuild workspace, so it costs
/// about a second per gate. It reads every type definition with <c>System.Reflection.Metadata</c> and every type's
/// documents from the portable PDB beside its assembly, and answers two things: the authored population (the
/// census's rule, applied to those documents) and the distinct (outermost authored type, outermost product type)
/// pairs — the census's unit of "uses" (<c>RawEdge.Pairs</c>), counted over the walk's own population.
/// </summary>
/// <remarks>
/// <para>
/// <b>Population.</b> The C# compiler's synthesized types are not authored, by the census's population rule
/// (<c>tools/ArchCensus/CompiledPopulation.cs</c>): <c>&lt;Module&gt;</c> and every type carrying
/// <c>[CompilerGenerated]</c>, with the types nested in them. A closure, an iterator or an async state machine nested
/// in a type is that type's code, so its references fold into it. A type is GENERATED only when every document that
/// declares it is a generated output (<see cref="GeneratedDocument"/>); a partial with one hand-written document is
/// authored — which an attribute test cannot see (the ANTLR parser carries <c>[GeneratedCode]</c> on its merged type
/// although its hand partial makes it authored). A type's documents include its nested types' (a nested type is
/// declared inside a declaration of its container, in the same document: the parser's hand partial declares only a
/// member of its nested <c>CompilationUnitContext</c>), and a type with none at all is declared in its declaring type's.
/// </para>
/// <para>
/// <b>What a reference is.</b> Every type named by the base type, the interface implementations, the generic parameter
/// constraints, the field, property, event and method signatures, each body's local-variable signature, its
/// exception handlers' catch types and its IL operand tokens (the opcode table is read from <see cref="OpCodes"/>, so
/// the decoder owns no opcode list), and each custom attribute's constructor and its <c>typeof</c> arguments; a
/// generic instantiation contributes each of its arguments. A member reference contributes the type that declares the
/// member, as the census's <c>TargetType</c> does. The walk cannot see what the C# compiler erased (an inlined
/// <c>const</c>, a <c>nameof</c>), which is why the edges file keeps the census's count beside the walk's.
/// </para>
/// </remarks>
internal sealed class TypeReferenceWalk
{
    /// <summary>The PDB custom debug information the C# compiler writes for a type with no method body:
    /// <c>TypeDefinitionDocuments</c>, a list of compressed document row numbers.</summary>
    private static readonly Guid TypeDefinitionDocuments = new("932E74BC-DBA9-4478-8D46-0F32A7BAB3D3");

    private readonly Dictionary<string, WalkedType> types = new(StringComparer.Ordinal);
    private readonly HashSet<TypePair> pairs = [];

    private TypeReferenceWalk()
    {
    }

    /// <summary>Every type definition the walk read that the compiler did not synthesize, by full metadata name.</summary>
    public IReadOnlyDictionary<string, WalkedType> Types => types;

    /// <summary>The distinct cross-type dependencies between outermost types, a type's use of itself excluded.</summary>
    public IReadOnlySet<TypePair> Pairs => pairs;

    /// <summary>The namespace of an outermost product type the walk read.</summary>
    public string NamespaceOf(string outermost) => types[outermost].Namespace;

    /// <summary>Walks <paramref name="assemblies"/> (each with its portable PDB beside it). A document's generated-ness
    /// is judged by its path relative to the project directory <paramref name="projectDirectoryOf"/> names for its
    /// assembly (the census's project-relative rule).</summary>
    public static TypeReferenceWalk Read(IReadOnlyList<string> assemblies, Func<string, string> projectDirectoryOf)
    {
        var walk = new TypeReferenceWalk();
        var readers = new List<AssemblyReader>();
        try
        {
            foreach (string path in assemblies)
            {
                readers.Add(new AssemblyReader(path, projectDirectoryOf(Path.GetFileNameWithoutExtension(path))));
            }

            var product = readers.Select(r => r.AssemblyName).ToHashSet(StringComparer.Ordinal);
            var enums = new Dictionary<string, PrimitiveTypeCode>(StringComparer.Ordinal);
            foreach (AssemblyReader r in readers)
            {
                r.Inventory(walk.types, enums);
            }

            foreach (AssemblyReader r in readers)
            {
                r.CollectPairs(product, enums, walk.types, walk.pairs);
            }
        }
        finally
        {
            foreach (AssemblyReader r in readers)
            {
                r.Dispose();
            }
        }

        return walk;
    }

    /// <summary>
    /// THE census's generated-document rule (<c>tools/ArchCensus/GeneratedCode.cs</c>, which a source generator's output
    /// also meets by its path under <c>obj</c>): a document is generated when its project-relative path has an
    /// <c>obj</c> or <c>Generated</c> directory segment, when its name ends in <c>.g.cs</c>, <c>.g.i.cs</c> or
    /// <c>.Designer.cs</c>, or when its first comment carries <c>&lt;auto-generated</c>.
    /// </summary>
    internal static bool GeneratedDocument(string projectRelativePath, Func<string?> firstComment)
    {
        string[] segments = projectRelativePath.Split('/', '\\');
        if (segments.SkipLast(1).Any(s => s.Equals("obj", StringComparison.OrdinalIgnoreCase)
                                          || s.Equals("Generated", StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        if (new[] { ".g.cs", ".g.i.cs", ".Designer.cs" }.Any(s => projectRelativePath.EndsWith(s, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        return firstComment()?.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) == true;
    }

    /// <summary>The first comment of a C# file's leading trivia (blank lines and preprocessor directives before it are
    /// trivia too), or null when its first token comes first or the file is absent.</summary>
    internal static string? FirstComment(string path)
    {
        if (!File.Exists(path))
        {
            return null;
        }

        using var text = new StreamReader(path);
        string? line;
        while ((line = text.ReadLine()) is not null)
        {
            string t = line.TrimStart('﻿', ' ', '\t');
            if (t.Length == 0 || t.StartsWith('#'))
            {
                continue;
            }

            if (t.StartsWith("//", StringComparison.Ordinal))
            {
                return t;
            }

            if (!t.StartsWith("/*", StringComparison.Ordinal))
            {
                return null;
            }

            var block = new System.Text.StringBuilder(t);
            while (!block.ToString().Contains("*/", StringComparison.Ordinal) && (line = text.ReadLine()) is not null)
            {
                block.Append('\n').Append(line);
            }

            return block.ToString();
        }

        return null;
    }

    /// <summary>One product assembly and its PDB, open for the walk's two passes.</summary>
    private sealed class AssemblyReader : IDisposable
    {
        private readonly PEReader pe;
        private readonly MetadataReaderProvider pdbProvider;
        private readonly MetadataReader md;
        private readonly MetadataReader pdb;
        private readonly string projectDirectory;
        private readonly Dictionary<TypeDefinitionHandle, string?> outermost = [];
        private readonly Dictionary<TypeDefinitionHandle, bool> contributes = [];

        public AssemblyReader(string path, string projectDirectory)
        {
            string pdbPath = Path.ChangeExtension(path, ".pdb");
            if (!File.Exists(path) || !File.Exists(pdbPath))
            {
                throw new FileNotFoundException(
                    $"the architecture walk needs the built product assembly and its portable PDB (build WiseOwl.Cobol.sln): {path}");
            }

            pe = new PEReader(File.OpenRead(path));
            md = pe.GetMetadataReader();
            pdbProvider = MetadataReaderProvider.FromPortablePdbStream(File.OpenRead(pdbPath));
            pdb = pdbProvider.GetMetadataReader();
            this.projectDirectory = projectDirectory;
            AssemblyName = md.GetString(md.GetAssemblyDefinition().Name);
        }

        public string AssemblyName { get; }

        public MethodBodyBlock Body(int relativeVirtualAddress) => pe.GetMethodBody(relativeVirtualAddress);

        public void Dispose()
        {
            pdbProvider.Dispose();
            pe.Dispose();
        }

        /// <summary>Pass 1: every type the compiler did not synthesize, with its outermost type, namespace and
        /// generated-ness; and every enum's underlying type (a custom attribute's enum argument needs it to decode).</summary>
        public void Inventory(Dictionary<string, WalkedType> types, Dictionary<string, PrimitiveTypeCode> enums)
        {
            var documentGenerated = new Dictionary<DocumentHandle, bool>();
            foreach (TypeDefinitionHandle h in md.TypeDefinitions)
            {
                if (OutermostOf(h) is not { } top || Synthesized(h))
                {
                    continue;
                }

                string name = FullName(h);
                bool generated = DocumentsOf(h).All(d => GeneratedOf(d, documentGenerated));
                TypeDefinitionHandle root = h;
                while (!md.GetTypeDefinition(root).GetDeclaringType().IsNil)
                {
                    root = md.GetTypeDefinition(root).GetDeclaringType();
                }

                types.Add(name, new WalkedType(name, top, md.GetString(md.GetTypeDefinition(root).Namespace), generated));
                if (EnumUnderlying(h) is { } code)
                {
                    enums[name] = code;
                }
            }
        }

        /// <summary>Pass 2: the pairs from every type whose nearest non-synthesized type (itself, or the type a closure
        /// is nested in) is authored, each end folded to its outermost type.</summary>
        public void CollectPairs(IReadOnlySet<string> product, IReadOnlyDictionary<string, PrimitiveTypeCode> enums,
            IReadOnlyDictionary<string, WalkedType> types, HashSet<TypePair> pairs)
        {
            var attributeTypes = new AttributeTypeProvider(types, enums);
            foreach (TypeDefinitionHandle h in md.TypeDefinitions)
            {
                if (OutermostOf(h) is not { } from || !Contributes(h, types))
                {
                    continue;
                }

                var targets = new HashSet<string>(StringComparer.Ordinal);
                new TypeVisit(md, product, attributeTypes, this, targets).Type(h);
                foreach (string to in targets)
                {
                    if (to != from)
                    {
                        pairs.Add(new TypePair(from, to));
                    }
                }
            }
        }

        /// <summary>The full name of the outermost type of a definition, or null for <c>&lt;Module&gt;</c> and a type
        /// the compiler synthesized at the top level (<c>&lt;PrivateImplementationDetails&gt;</c>, an anonymous type, an
        /// embedded attribute).</summary>
        public string? OutermostOf(TypeDefinitionHandle h)
        {
            if (outermost.TryGetValue(h, out string? cached))
            {
                return cached;
            }

            TypeDefinitionHandle root = h;
            while (!md.GetTypeDefinition(root).GetDeclaringType().IsNil)
            {
                root = md.GetTypeDefinition(root).GetDeclaringType();
            }

            TypeDefinition top = md.GetTypeDefinition(root);
            string? name = md.GetString(top.Name) == "<Module>" || CompilerGenerated(top) ? null : FullName(root);
            outermost[h] = name;
            return name;
        }

        /// <summary>The full name of an outermost type a TypeRef names in another product assembly, or null.</summary>
        public static string? ProductOutermost(MetadataReader md, TypeReferenceHandle h, IReadOnlySet<string> product)
        {
            TypeReference r = md.GetTypeReference(h);
            while (r.ResolutionScope.Kind == HandleKind.TypeReference)
            {
                r = md.GetTypeReference((TypeReferenceHandle)r.ResolutionScope);
            }

            if (r.ResolutionScope.Kind != HandleKind.AssemblyReference
                || !product.Contains(md.GetString(md.GetAssemblyReference((AssemblyReferenceHandle)r.ResolutionScope).Name)))
            {
                return null;
            }

            string ns = md.GetString(r.Namespace);
            string name = md.GetString(r.Name);
            return ns.Length == 0 ? name : $"{ns}.{name}";
        }

        private bool Contributes(TypeDefinitionHandle h, IReadOnlyDictionary<string, WalkedType> types)
        {
            if (contributes.TryGetValue(h, out bool cached))
            {
                return cached;
            }

            TypeDefinitionHandle owner = h;
            while (Synthesized(owner))
            {
                owner = md.GetTypeDefinition(owner).GetDeclaringType();
            }

            bool result = !types[FullName(owner)].Generated;
            contributes[h] = result;
            return result;
        }

        /// <summary>A type the compiler synthesized inside an authored type: <c>[CompilerGenerated]</c> on it or on a
        /// type between it and its outermost type (which <see cref="OutermostOf"/> has already admitted).</summary>
        private bool Synthesized(TypeDefinitionHandle h)
        {
            for (TypeDefinitionHandle t = h; !t.IsNil; t = md.GetTypeDefinition(t).GetDeclaringType())
            {
                if (CompilerGenerated(md.GetTypeDefinition(t)))
                {
                    return true;
                }
            }

            return false;
        }

        private bool CompilerGenerated(TypeDefinition type)
        {
            foreach (CustomAttributeHandle a in type.GetCustomAttributes())
            {
                if (AttributeTypeName(md, md.GetCustomAttribute(a).Constructor) == "System.Runtime.CompilerServices.CompilerGeneratedAttribute")
                {
                    return true;
                }
            }

            return false;
        }

        public static string AttributeTypeName(MetadataReader md, EntityHandle ctor)
        {
            EntityHandle type = ctor.Kind switch
            {
                HandleKind.MemberReference => md.GetMemberReference((MemberReferenceHandle)ctor).Parent,
                HandleKind.MethodDefinition => md.GetMethodDefinition((MethodDefinitionHandle)ctor).GetDeclaringType(),
                _ => default,
            };
            return type.Kind switch
            {
                HandleKind.TypeReference => $"{md.GetString(md.GetTypeReference((TypeReferenceHandle)type).Namespace)}.{md.GetString(md.GetTypeReference((TypeReferenceHandle)type).Name)}",
                HandleKind.TypeDefinition => $"{md.GetString(md.GetTypeDefinition((TypeDefinitionHandle)type).Namespace)}.{md.GetString(md.GetTypeDefinition((TypeDefinitionHandle)type).Name)}",
                _ => "",
            };
        }

        public string FullName(TypeDefinitionHandle h)
        {
            TypeDefinition t = md.GetTypeDefinition(h);
            string name = md.GetString(t.Name);
            TypeDefinitionHandle outer = t.GetDeclaringType();
            if (!outer.IsNil)
            {
                return $"{FullName(outer)}+{name}";
            }

            string ns = md.GetString(t.Namespace);
            return ns.Length == 0 ? name : $"{ns}.{name}";
        }

        /// <summary>The documents that declare a type: its own (<see cref="OwnDocuments"/>) and every nested type's, since
        /// a nested type is declared inside a declaration of its container in the same document (a partial whose hand
        /// half holds only a nested member is still a hand document of the container); failing all of those, its
        /// declaring type's own documents.</summary>
        private IReadOnlyCollection<DocumentHandle> DocumentsOf(TypeDefinitionHandle h)
        {
            var documents = new HashSet<DocumentHandle>();
            var pending = new Stack<TypeDefinitionHandle>([h]);
            while (pending.TryPop(out TypeDefinitionHandle t))
            {
                OwnDocuments(t, documents);
                foreach (TypeDefinitionHandle nested in md.GetTypeDefinition(t).GetNestedTypes())
                {
                    pending.Push(nested);
                }
            }

            for (TypeDefinitionHandle t = md.GetTypeDefinition(h).GetDeclaringType(); !t.IsNil && documents.Count == 0;
                 t = md.GetTypeDefinition(t).GetDeclaringType())
            {
                OwnDocuments(t, documents);
            }

            if (documents.Count == 0)
            {
                throw new InvalidOperationException(
                    $"the PDB of {AssemblyName} names no document for {FullName(h)}: the census's generated rule cannot be applied to it");
            }

            return documents;
        }

        /// <summary>A type's own documents: its methods' sequence-point documents and its
        /// <see cref="TypeDefinitionDocuments"/> (written for a type with no method body).</summary>
        private void OwnDocuments(TypeDefinitionHandle t, HashSet<DocumentHandle> documents)
        {
            foreach (MethodDefinitionHandle m in md.GetTypeDefinition(t).GetMethods())
            {
                MethodDebugInformation info = pdb.GetMethodDebugInformation(m.ToDebugInformationHandle());
                if (!info.Document.IsNil)
                {
                    documents.Add(info.Document);
                }

                if (!info.SequencePointsBlob.IsNil)
                {
                    foreach (SequencePoint sp in info.GetSequencePoints())
                    {
                        documents.Add(sp.Document);
                    }
                }
            }

            foreach (CustomDebugInformationHandle c in pdb.GetCustomDebugInformation(t))
            {
                CustomDebugInformation info = pdb.GetCustomDebugInformation(c);
                if (pdb.GetGuid(info.Kind) != TypeDefinitionDocuments)
                {
                    continue;
                }

                BlobReader blob = pdb.GetBlobReader(info.Value);
                while (blob.RemainingBytes > 0)
                {
                    documents.Add(MetadataTokens.DocumentHandle(blob.ReadCompressedInteger()));
                }
            }
        }

        private bool GeneratedOf(DocumentHandle d, Dictionary<DocumentHandle, bool> cache)
        {
            if (cache.TryGetValue(d, out bool known))
            {
                return known;
            }

            string path = pdb.GetString(pdb.GetDocument(d).Name);
            string normalized = path.Replace('\\', '/');
            string root = projectDirectory.Replace('\\', '/').TrimEnd('/') + "/";
            string relative = normalized.StartsWith(root, StringComparison.OrdinalIgnoreCase) ? normalized[root.Length..] : normalized;
            bool generated = GeneratedDocument(relative, () => FirstComment(path));
            cache[d] = generated;
            return generated;
        }

        private PrimitiveTypeCode? EnumUnderlying(TypeDefinitionHandle h)
        {
            TypeDefinition t = md.GetTypeDefinition(h);
            if (t.BaseType.Kind != HandleKind.TypeReference)
            {
                return null;
            }

            TypeReference b = md.GetTypeReference((TypeReferenceHandle)t.BaseType);
            if (md.GetString(b.Namespace) != "System" || md.GetString(b.Name) != "Enum")
            {
                return null;
            }

            foreach (FieldDefinitionHandle f in t.GetFields())
            {
                FieldDefinition field = md.GetFieldDefinition(f);
                if ((field.Attributes & FieldAttributes.Static) == 0)
                {
                    return field.DecodeSignature(new UnderlyingTypeProvider(), null);
                }
            }

            return null;
        }
    }

    /// <summary>The walk of one type definition: every type its metadata names, folded to product outermost types.</summary>
    private sealed class TypeVisit(MetadataReader md, IReadOnlySet<string> product,
        AttributeTypeProvider attributeTypes, AssemblyReader assembly, HashSet<string> targets)
        : ISignatureTypeProvider<bool, object?>
    {
        private static readonly OpCode[] OneByte = new OpCode[0x100];
        private static readonly OpCode[] TwoByte = new OpCode[0x100];

        static TypeVisit()
        {
            foreach (FieldInfo f in typeof(OpCodes).GetFields(BindingFlags.Public | BindingFlags.Static))
            {
                var op = (OpCode)f.GetValue(null)!;
                ushort value = unchecked((ushort)op.Value);
                (op.Size == 1 ? OneByte : TwoByte)[value & 0xFF] = op;
            }
        }

        public void Type(TypeDefinitionHandle h)
        {
            TypeDefinition t = md.GetTypeDefinition(h);
            Attributes(t.GetCustomAttributes());
            Entity(t.BaseType);
            foreach (InterfaceImplementationHandle i in t.GetInterfaceImplementations())
            {
                InterfaceImplementation impl = md.GetInterfaceImplementation(i);
                Entity(impl.Interface);
                Attributes(impl.GetCustomAttributes());
            }

            GenericParameters(t.GetGenericParameters());
            foreach (FieldDefinitionHandle f in t.GetFields())
            {
                FieldDefinition field = md.GetFieldDefinition(f);
                field.DecodeSignature(this, null);
                Attributes(field.GetCustomAttributes());
            }

            foreach (PropertyDefinitionHandle p in t.GetProperties())
            {
                PropertyDefinition property = md.GetPropertyDefinition(p);
                property.DecodeSignature(this, null);
                Attributes(property.GetCustomAttributes());
            }

            foreach (EventDefinitionHandle e in t.GetEvents())
            {
                EventDefinition ev = md.GetEventDefinition(e);
                Entity(ev.Type);
                Attributes(ev.GetCustomAttributes());
            }

            foreach (MethodDefinitionHandle m in t.GetMethods())
            {
                Method(m);
            }
        }

        private void Method(MethodDefinitionHandle h)
        {
            MethodDefinition m = md.GetMethodDefinition(h);
            m.DecodeSignature(this, null);
            Attributes(m.GetCustomAttributes());
            GenericParameters(m.GetGenericParameters());
            foreach (ParameterHandle p in m.GetParameters())
            {
                Attributes(md.GetParameter(p).GetCustomAttributes());
            }

            if (m.RelativeVirtualAddress == 0)
            {
                return;
            }

            MethodBodyBlock body = assembly.Body(m.RelativeVirtualAddress);
            if (!body.LocalSignature.IsNil)
            {
                md.GetStandaloneSignature(body.LocalSignature).DecodeLocalSignature(this, null);
            }

            foreach (ExceptionRegion region in body.ExceptionRegions)
            {
                Entity(region.CatchType);
            }

            Instructions(body.GetILReader());
        }

        /// <summary>Every token operand of a body's IL, the opcode table read from <see cref="OpCodes"/>.</summary>
        private void Instructions(BlobReader il)
        {
            while (il.RemainingBytes > 0)
            {
                byte b = il.ReadByte();
                OpCode op = b == 0xFE ? TwoByte[il.ReadByte()] : OneByte[b];
                switch (op.OperandType)
                {
                    case OperandType.InlineNone:
                        break;
                    case OperandType.ShortInlineBrTarget or OperandType.ShortInlineI or OperandType.ShortInlineVar:
                        il.Offset += 1;
                        break;
                    case OperandType.InlineVar:
                        il.Offset += 2;
                        break;
                    case OperandType.InlineI8 or OperandType.InlineR:
                        il.Offset += 8;
                        break;
                    case OperandType.InlineSwitch:
                        int targets = il.ReadInt32();   // read first: `Offset += 4 * ReadInt32()` reads Offset before the count advances it
                        il.Offset += 4 * targets;
                        break;
                    case OperandType.InlineField or OperandType.InlineMethod or OperandType.InlineTok
                        or OperandType.InlineType or OperandType.InlineSig:
                        Entity(MetadataTokens.EntityHandle(il.ReadInt32()));
                        break;
                    default:
                        il.Offset += 4;   // InlineBrTarget, InlineI, InlineString, ShortInlineR
                        break;
                }
            }
        }

        private void GenericParameters(GenericParameterHandleCollection parameters)
        {
            foreach (GenericParameterHandle g in parameters)
            {
                GenericParameter gp = md.GetGenericParameter(g);
                Attributes(gp.GetCustomAttributes());
                foreach (GenericParameterConstraintHandle c in gp.GetConstraints())
                {
                    GenericParameterConstraint constraint = md.GetGenericParameterConstraint(c);
                    Entity(constraint.Type);
                    Attributes(constraint.GetCustomAttributes());
                }
            }
        }

        /// <summary>Each attribute's type and every <c>typeof</c> argument it carries.</summary>
        private void Attributes(CustomAttributeHandleCollection attributes)
        {
            foreach (CustomAttributeHandle a in attributes)
            {
                CustomAttribute attribute = md.GetCustomAttribute(a);
                Entity(attribute.Constructor);
                CustomAttributeValue<AttributeType> value;
                try
                {
                    value = attribute.DecodeValue(attributeTypes);
                }
                catch (BadImageFormatException e)
                {
                    throw new InvalidOperationException(
                        $"{assembly.AssemblyName}: a {AssemblyReader.AttributeTypeName(md, attribute.Constructor)} blob did not decode, so its typeof arguments are unread: {e.Message}", e);
                }

                foreach (CustomAttributeTypedArgument<AttributeType> arg in value.FixedArguments)
                {
                    Argument(arg);
                }

                foreach (CustomAttributeNamedArgument<AttributeType> arg in value.NamedArguments)
                {
                    Argument(new CustomAttributeTypedArgument<AttributeType>(arg.Type, arg.Value));
                }
            }
        }

        private void Argument(CustomAttributeTypedArgument<AttributeType> arg)
        {
            switch (arg.Value)
            {
                case AttributeType { Product: { } named }:
                    targets.Add(named);
                    break;
                case ImmutableArray<CustomAttributeTypedArgument<AttributeType>> items:
                    foreach (CustomAttributeTypedArgument<AttributeType> item in items)
                    {
                        Argument(item);
                    }

                    break;
            }
        }

        private void Entity(EntityHandle h)
        {
            if (h.IsNil)
            {
                return;
            }

            switch (h.Kind)
            {
                case HandleKind.TypeDefinition:
                    Add(assembly.OutermostOf((TypeDefinitionHandle)h));
                    break;
                case HandleKind.TypeReference:
                    Add(AssemblyReader.ProductOutermost(md, (TypeReferenceHandle)h, product));
                    break;
                case HandleKind.TypeSpecification:
                    md.GetTypeSpecification((TypeSpecificationHandle)h).DecodeSignature(this, null);
                    break;
                case HandleKind.MemberReference:
                    MemberReference member = md.GetMemberReference((MemberReferenceHandle)h);
                    if (member.Parent.Kind == HandleKind.MethodDefinition)
                    {
                        Entity(md.GetMethodDefinition((MethodDefinitionHandle)member.Parent).GetDeclaringType());
                    }
                    else if (member.Parent.Kind != HandleKind.ModuleReference)
                    {
                        Entity(member.Parent);
                    }

                    break;
                case HandleKind.MethodDefinition:
                    Entity(md.GetMethodDefinition((MethodDefinitionHandle)h).GetDeclaringType());
                    break;
                case HandleKind.FieldDefinition:
                    Entity(md.GetFieldDefinition((FieldDefinitionHandle)h).GetDeclaringType());
                    break;
                case HandleKind.MethodSpecification:
                    MethodSpecification spec = md.GetMethodSpecification((MethodSpecificationHandle)h);
                    Entity(spec.Method);
                    spec.DecodeSignature(this, null);
                    break;
                case HandleKind.StandaloneSignature:
                    StandaloneSignature sig = md.GetStandaloneSignature((StandaloneSignatureHandle)h);
                    if (sig.GetKind() == StandaloneSignatureKind.Method)
                    {
                        sig.DecodeMethodSignature(this, null);
                    }
                    else
                    {
                        sig.DecodeLocalSignature(this, null);
                    }

                    break;
                default:
                    throw new InvalidOperationException($"{assembly.AssemblyName}: the walk has no rule for a {h.Kind} token");
            }
        }

        private void Add(string? outermost)
        {
            if (outermost is not null)
            {
                targets.Add(outermost);
            }
        }

        public bool GetArrayType(bool elementType, ArrayShape shape) => false;
        public bool GetByReferenceType(bool elementType) => false;
        public bool GetFunctionPointerType(MethodSignature<bool> signature) => false;
        public bool GetGenericInstantiation(bool genericType, ImmutableArray<bool> typeArguments) => false;
        public bool GetGenericMethodParameter(object? genericContext, int index) => false;
        public bool GetGenericTypeParameter(object? genericContext, int index) => false;
        public bool GetModifiedType(bool modifier, bool unmodifiedType, bool isRequired) => false;
        public bool GetPinnedType(bool elementType) => false;
        public bool GetPointerType(bool elementType) => false;
        public bool GetPrimitiveType(PrimitiveTypeCode typeCode) => false;
        public bool GetSZArrayType(bool elementType) => false;

        public bool GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind)
        {
            Add(assembly.OutermostOf(handle));
            return false;
        }

        public bool GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind)
        {
            Add(AssemblyReader.ProductOutermost(reader, handle, product));
            return false;
        }

        public bool GetTypeFromSpecification(MetadataReader reader, object? genericContext, TypeSpecificationHandle handle, byte rawTypeKind) =>
            reader.GetTypeSpecification(handle).DecodeSignature(this, genericContext);
    }

    /// <summary>A type a custom attribute blob names: its full name, and the product outermost type it folds into
    /// (null outside the product). <c>System.Type</c> is the type of a <c>typeof</c> argument.</summary>
    private sealed record AttributeType(string FullName, string? Product);

    /// <summary>Decodes a custom attribute blob's argument types: <c>typeof</c> arguments arrive by serialized name.</summary>
    private sealed class AttributeTypeProvider(IReadOnlyDictionary<string, WalkedType> types,
        IReadOnlyDictionary<string, PrimitiveTypeCode> enums) : ICustomAttributeTypeProvider<AttributeType>
    {
        public AttributeType GetPrimitiveType(PrimitiveTypeCode typeCode) => new(typeCode.ToString(), null);

        public AttributeType GetSystemType() => new("System.Type", null);

        public AttributeType GetSZArrayType(AttributeType elementType) => new(elementType.FullName + "[]", elementType.Product);

        public AttributeType GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind) =>
            Named(NameOf(reader, handle));

        public AttributeType GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind) =>
            Named(NameOf(reader, handle));

        /// <summary>A serialized type name (<c>Ns.Outer+Nested, Assembly, …</c>, generic arguments in brackets) names a
        /// product type when the walk read a type of that name.</summary>
        public AttributeType GetTypeFromSerializedName(string name)
        {
            int depth = 0, end = name.Length;
            for (int i = 0; i < name.Length && end == name.Length; i++)
            {
                depth += name[i] == '[' ? 1 : name[i] == ']' ? -1 : 0;
                end = name[i] == ',' && depth == 0 ? i : end;
            }

            string typeName = name[..end].Trim();
            int generic = typeName.IndexOf('[', StringComparison.Ordinal);
            return Named(generic < 0 ? typeName : typeName[..generic]);
        }

        /// <summary>A product enum's underlying type is read from its <c>value__</c> field; a framework enum an attribute
        /// argument names is taken as <c>int</c>, the underlying type of every framework attribute enum the product
        /// passes. A wrong guess misaligns the rest of that blob, which then usually fails to decode, and
        /// <see cref="TypeVisit"/> rethrows the failure naming the attribute.</summary>
        public PrimitiveTypeCode GetUnderlyingEnumType(AttributeType type) =>
            enums.TryGetValue(type.FullName, out PrimitiveTypeCode code) ? code : PrimitiveTypeCode.Int32;

        public bool IsSystemType(AttributeType type) => type.FullName == "System.Type";

        private AttributeType Named(string fullName) =>
            new(fullName, types.TryGetValue(fullName, out WalkedType? t) ? t.Outermost : null);

        private static string NameOf(MetadataReader reader, TypeDefinitionHandle h)
        {
            TypeDefinition d = reader.GetTypeDefinition(h);
            string name = reader.GetString(d.Name);
            if (!d.GetDeclaringType().IsNil)
            {
                return $"{NameOf(reader, d.GetDeclaringType())}+{name}";
            }

            string ns = reader.GetString(d.Namespace);
            return ns.Length == 0 ? name : $"{ns}.{name}";
        }

        private static string NameOf(MetadataReader reader, TypeReferenceHandle h)
        {
            TypeReference r = reader.GetTypeReference(h);
            string name = reader.GetString(r.Name);
            if (r.ResolutionScope.Kind == HandleKind.TypeReference)
            {
                return $"{NameOf(reader, (TypeReferenceHandle)r.ResolutionScope)}+{name}";
            }

            string ns = reader.GetString(r.Namespace);
            return ns.Length == 0 ? name : $"{ns}.{name}";
        }
    }

    /// <summary>Reads an enum's <c>value__</c> field type.</summary>
    private sealed class UnderlyingTypeProvider : ISignatureTypeProvider<PrimitiveTypeCode, object?>
    {
        public PrimitiveTypeCode GetPrimitiveType(PrimitiveTypeCode typeCode) => typeCode;
        public PrimitiveTypeCode GetArrayType(PrimitiveTypeCode elementType, ArrayShape shape) => throw Unexpected();
        public PrimitiveTypeCode GetByReferenceType(PrimitiveTypeCode elementType) => throw Unexpected();
        public PrimitiveTypeCode GetFunctionPointerType(MethodSignature<PrimitiveTypeCode> signature) => throw Unexpected();
        public PrimitiveTypeCode GetGenericInstantiation(PrimitiveTypeCode genericType, ImmutableArray<PrimitiveTypeCode> typeArguments) => throw Unexpected();
        public PrimitiveTypeCode GetGenericMethodParameter(object? genericContext, int index) => throw Unexpected();
        public PrimitiveTypeCode GetGenericTypeParameter(object? genericContext, int index) => throw Unexpected();
        public PrimitiveTypeCode GetModifiedType(PrimitiveTypeCode modifier, PrimitiveTypeCode unmodifiedType, bool isRequired) => unmodifiedType;
        public PrimitiveTypeCode GetPinnedType(PrimitiveTypeCode elementType) => throw Unexpected();
        public PrimitiveTypeCode GetPointerType(PrimitiveTypeCode elementType) => throw Unexpected();
        public PrimitiveTypeCode GetSZArrayType(PrimitiveTypeCode elementType) => throw Unexpected();
        public PrimitiveTypeCode GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind) => throw Unexpected();
        public PrimitiveTypeCode GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind) => throw Unexpected();
        public PrimitiveTypeCode GetTypeFromSpecification(MetadataReader reader, object? genericContext, TypeSpecificationHandle handle, byte rawTypeKind) => throw Unexpected();

        private static InvalidOperationException Unexpected() => new("an enum's value__ field is not a primitive type");
    }
