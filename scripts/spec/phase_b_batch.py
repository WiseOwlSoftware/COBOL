"""Prepare a Phase-B adjudication batch: one input file per SUBJECT, holding the full text of its rules.

    python scripts/spec/phase_b_batch.py 15.32-15.44             # a clause range
    python scripts/spec/phase_b_batch.py 14.9.1 14.9.2           # explicit clauses
    python scripts/spec/phase_b_batch.py 14 --max-rules 20        # a whole clause, agent-sized
    python scripts/spec/phase_b_batch.py 15.32-15.44 --out DIR    # somewhere other than the default scratchpad

⚠ ONE SUBJECT IS NOT ALWAYS ONE AGENT. The `subject` key is the statement name in §14 and the clause name in
§13, so it generalises past §15's functions — but the SIZE does not. The four §15 batches that have actually run
topped out at 18 rules per agent; SET carries 98, PICTURE 72, SPECIAL-NAMES 81. `--max-rules` (default 20) splits
an oversized subject at CLAUSE boundaries (`.2` format / `.3` syntax rules / `.4` general rules are different
questions, so the seam is free), leaves a fitting subject WHOLE, and gives each part its siblings and the whole
subject's clause map so no agent adjudicates a slice believing it is the set.

⛔ ONE AGENT, ONE INPUT FILE — never "read the shared catalog and take element k". Agents miscount the index, and
one fan-out cost four double-processed clusters and five skipped entirely (`feedback_agent_dispatch`). This writes
a self-contained file per subject and prints the slug list to paste into the workflow script.

⚠ ALREADY-ADJUDICATED RULES ARE EXCLUDED automatically — a rule with a verdict in the inventory is not re-issued,
so re-running after a partial batch is safe and resumable.

⭐ EVERY FILE ALSO CARRIES A DOSSIER — the discovery the agent would otherwise repeat. Batch 8 (2026-09-01) spent
574M cache-read tokens over 39 agents for 224 rows, and the bulk of each agent's ~120 turns was the SAME three
greps: where is the grammar rule, where is the binder/emitter, where are the tests. That search has one answer per
subject and it was being bought 39 times. The dossier computes it once, from the catalog's own `subject` field and
the subject's clause numbers, and pastes it into every part file: grammar rules, citing source files, citing tests,
the `docs/CONFORMANCE.md` determinations, the `kb/Work/` notes that already own these rows, and the citing
`docs/DIAGNOSTICS.md` entries. **The agent's job becomes VERIFY, not SEARCH.** `--no-dossier` turns it off.

⛔ THE DOSSIER IS A MAP, NOT THE TERRITORY, AND ITS SILENCE IS NOT EVIDENCE. It is a keyword-and-citation
selector, so it is evidence about what it RETURNED and says nothing about what it dropped
(`feedback_measure_the_selectors_complement`: `work.py next`'s own filter hid nine harmful items for months while
looking perfectly healthy). An empty `grammar` list means "this derivation found none", never "the compiler has
none" — a §8 concept subject has no keyword to search with at all. Every file therefore repeats that sentence to
the agent in `how-to-read`, so a NOT-IMPLEMENTED verdict is never returned on the dossier's silence alone.

WHY THIS IS A SCRIPT AND NOT PASTED PYTHON. The first three batches were generated by inline snippets, which meant
the filter logic was retyped each time and the exclusion rule lived only in a transcript. The batches are the
project's road to v1.0 and there will be dozens; the generator belongs in the repo with them.

THE PROMPT THAT DRIVES THE AGENTS lives with the workflow, not here — see
`docs/rearchitecture/DESIGN-spec-conformance-review.md` §8, which records what a batch prompt MUST carry (the
spec-derived test-ref rule, the "editions never from the catalog row" warning, the CONFORMS-costs-something rule,
and the adversarial refute stage), and §9 for the dossier's contract.
"""
