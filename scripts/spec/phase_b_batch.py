# The pre-computed discovery handed to every agent. See the module docstring for WHY; what follows is HOW.

#: Everything the dossier scans, as (root, glob). Read once per run and reused across every subject in the batch.
#: ⚠ `tests/nist` is deliberately absent from the `.cob` roots: 459 machine-generated CCVS cards, 30 MB — twice
