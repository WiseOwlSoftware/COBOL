CORPUS = {
    "grammar": [("src/Cobol.Net.Frontend/Grammar", "**/*.g4")],
    "source": [("src", "Cobol.Net.*/**/*.cs")],
    "tests": [("tests", "**/*.cs"),
              ("tests/conformance", "**/*.cob"),
              ("tests/characterization", "**/*.cob")],
}
SKIP_DIRS = ("/obj/", "/bin/", "/Generated/")

#: Caps. The dossier is a MAP: an input file that grows past agent-sized has traded one search problem for
#: another. Every category reports `truncated` so a cut is visible rather than silent.
MAX_LINES = 40          # citing lines kept per category
MAX_PER_FILE = 6        # citing lines kept per file, before the round-robin trim
MAX_FILES = 40          # keyword-named files kept per category
MAX_RULES = 8           # grammar rules quoted
MAX_RULE_LINES = 40     # lines of one rule's text
MAX_LEAD_COMMENT = 12   # lines of the comment block above a rule (it usually carries the existing ISO citation)
SNIP = 300              # characters of one citing line (docs/CONFORMANCE.md rows run to 4,000)

#: ALL-CAPS words that are in a subject name but are not a construct to search for. ⚠ This is NOT the
#: construct→file map CLAUDE.md rule 8 forbids — nothing here names a file, a rule or a subsystem, and adding a
#: construct never touches it. `COBOL` is the one that has to be here: as a keyword it matches every assembly
#: (`src/Cobol.Net.*`), every grammar file (`CobolLexer.g4`) and every test, i.e. everything and therefore nothing.
#: ⛔ IT DELIBERATELY DOES NOT HOLD `TO`, `OF`, `WHEN`, `ALL`… Those look like stopwords and are COBOL RESERVED
#: WORDS carrying a construct's identity: dropping them turns `GO TO statement` into `GO` and `BLANK WHEN ZERO
#: clause` into `BLANK`+`ZERO`, and the grammar's `goToStatement` / `blankWhenZeroClause` then stop matching
#: EXACTLY — which is the rank that decides what survives the 8-rule cap. The noise they would add elsewhere is
#: held off structurally instead, by `named`'s token rule, not by a longer stopword list.
KEYWORD_NOISE = {"COBOL", "ISO", "IEC", "THE", "AND", "OR", "A", "AN"}
#: The trailing role word in a catalog `subject` — "OPEN statement", "VALUE clause", "TRIM function". ⚠ ONE
#: regex serves both readers: `.sub` strips the role and everything after it to leave the construct name, and
#: group 1 IS the role. Written twice it would be one rule in two places, and the two spellings would drift.
SUBJECT_ROLE = re.compile(r"\s+(statement|clause|function|paragraph|directive|phrase|entry|register)s?\b.*$",
                          re.IGNORECASE)
#: A construct word in a subject name: an ALL-CAPS COBOL word (`OPEN`, `BACKGROUND-COLOR`), or a hyphenated
#: lowercase COBOL term, which the standard capitalises as prose — `Entry-name`, `Level-number`,
#: `Condition-name`, `Data-address-identifier`. The second arm is not decoration: without it `Entry-name clause`
#: derives NO keyword at all and its dossier arrives with the grammar and file-name halves empty.
#: ⛔ THE HYPHENATED-PROSE ARM COMES FIRST. ANTLR-style alternation takes the first arm that matches at a
#: position, and on `Entry-name` the ALL-CAPS arm matches the single letter `E` — the scan then resumed at `n`
#: and produced the keyword `NTRY-NAME`, which matches nothing and looks like a derivation rather than a bug.
CAPS_WORD = re.compile(r"[A-Za-z][a-z]+(?:-[a-z]+)+|[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*")
#: Prose fallback: lowercase words long enough to be a real search term. `data`, `item`, `used` are not.
PROSE_WORD = re.compile(r"[A-Za-z][a-z]{5,}")
PROSE_NOISE = {"implementor", "defined", "specified", "standard", "meaning", "between", "certain", "several",
               "whether", "another", "including", "associated"}
#: `openStatement` → open · statement; `SPECIAL_NAMES` → special · names.
CAMEL = re.compile(r"[A-Z]+(?![a-z])|[A-Z][a-z0-9]*|[a-z0-9]+")
#: Separator-stripper for file-name comparison. Compiled once: `named` runs it over the whole corpus per subject.
FLATTEN = re.compile(r"[^a-z0-9]")
#: An ANTLR rule header: a bare identifier on its own line (the project's parser-rule style) or `NAME : …`.
RULE_HEAD = re.compile(r"^([A-Za-z][A-Za-z0-9_]*)\s*(:.*)?$")
#: `GR-14.9.10.4-6` → the clause `14.9.10.4`. Catalog kinds: GR · SR · FMT · RV · AR · DOC.
RULE_ID = re.compile(r"^[A-Z]+-(\d+(?:\.\d+)*)-\d+$")
#: An Annex A.1 implementor-determination row in `docs/CONFORMANCE.md`, whose first cell is the A.1 item number.
A1_ROW = re.compile(r"^\|\s*(\d+)\s*\|")

