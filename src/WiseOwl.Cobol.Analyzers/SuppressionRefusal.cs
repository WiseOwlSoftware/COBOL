using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace WiseOwl.Cobol.Analyzers;

/// <summary>⛔ NO SUPPRESSION NAMES A RULE OF THE ONE-DECIDER ANALYZER (WOCA0003; kb/Work PB4950 round 11). The rules carry
/// <c>NotConfigurable</c>, which stops NoWarn, a configured severity and <c>#pragma</c>. A <c>[SuppressMessage]</c> or
/// <c>[UnconditionalSuppressMessage]</c> is applied by the analyzer driver after that, and NO analyzer diagnostic escapes it: a
/// refusal reported as a diagnostic was silenced by an attribute naming the refusal's own id, on the member or as a target-less
/// assembly-level suppression (two planted tests proved both). So the refusal is not a diagnostic of the analyzer. This generator
/// writes a <c>#error</c> into the compilation for each such attribute, and a <c>#error</c> is a compiler ERROR (CS1029), which no
/// suppression, pragma or NoWarn can reach.
/// <para>The attribute is bound, so its spelling (the full name, a <c>using</c> alias, the short name) does not matter, and its checkId (the second
/// positional argument, or the one named checkId, the only argument that names what a suppression silences) is read as the compiler
/// folds it, so an id held in a constant or built by concatenation is seen. An id in a Justification, Scope, Target or MessageId silences
/// nothing and is not refused.</para></summary>
[Generator(LanguageNames.CSharp)]
public sealed class SuppressionRefusal : IIncrementalGenerator
{
    /// <summary>The id the refusal names in its message.</summary>
    public const string Id = "WOCA0003";

    /// <summary>The suppression attributes, by metadata name.</summary>
    private static readonly ImmutableHashSet<string> SuppressionAttributes = ImmutableHashSet.Create(StringComparer.Ordinal,
        "System.Diagnostics.CodeAnalysis.SuppressMessageAttribute", "System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute");

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var refusals = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is AttributeSyntax,
                static (attribute, cancel) => Refusal((AttributeSyntax)attribute.Node, attribute.SemanticModel, cancel))
            .Where(static refusal => refusal is not null)
            .Collect();
        context.RegisterSourceOutput(refusals, static (output, found) =>
        {
            if (found.IsEmpty) return;
            var text = new StringBuilder("// <auto-generated/> WOCA0003: a suppression names a rule of the one-decider analyzer\n");
            foreach (string? refusal in found.OrderBy(r => r, StringComparer.Ordinal))
                text.Append("#error ").Append(refusal).Append('\n');
            output.AddSource("WOCA0003.SuppressionRefused.g.cs", text.ToString());
        });
    }

    /// <summary>The refusal's message for a suppression attribute that names a rule, or null.</summary>
    private static string? Refusal(AttributeSyntax attribute, SemanticModel model, CancellationToken cancel)
    {
        if (model.GetSymbolInfo(attribute, cancel).Symbol is not IMethodSymbol constructor
            || !SuppressionAttributes.Contains(constructor.ContainingType.ToDisplayString())
            || attribute.ArgumentList is null)
            return null;
        // The checkId alone names the rule a suppression silences (round 12, R11-2): the second positional argument, or the one named
        // checkId; a Justification, Scope, Target or MessageId that mentions an id silences nothing.
        var positional = attribute.ArgumentList.Arguments.Where(a => a.NameEquals is null).ToList();
        var checkId = positional.FirstOrDefault(a => a.NameColon?.Name.Identifier.ValueText == "checkId")
            ?? (positional.Count > 1 && positional[1].NameColon is null ? positional[1] : null);
        if (checkId is not null
            && model.GetConstantValue(checkId.Expression, cancel) is { HasValue: true, Value: string text } && RuleIdIn(text) is { } rule)
        {
            var at = attribute.GetLocation().GetLineSpan();
            return $"{Id}: the {constructor.ContainingType.Name} at {at.Path.Replace('\\', '/')}:{at.StartLinePosition.Line + 1} names "
                + $"'{rule}', a rule of the one-decider analyzer, which takes no exception; write the message through EditionInfo.Cite "
                + "(kb/Work PB4950, docs/VERSION_TEST_MATRIX_DESIGN.md P2.3a)";
        }
        return null;
    }

    /// <summary>The first rule id of the one-decider analyzer a text names (<c>WOCA</c> and four digits), or null.</summary>
    private static string? RuleIdIn(string text)
    {
        for (int at = text.IndexOf("WOCA", StringComparison.Ordinal); at >= 0; at = text.IndexOf("WOCA", at + 1, StringComparison.Ordinal))
            if (at + 8 <= text.Length && text.Substring(at + 4, 4).All(char.IsDigit))
                return text.Substring(at, 8);
        return null;
    }
}
