using CobolNet.Binding;
using CobolNet.Binding.Bound;
using CobolNet.CodeGen.Emit;
using CobolSharp.Compiler.Generated;

namespace CobolNet.CodeGen;

using Core = CobolParserCore;
using static CobolNet.CodeGen.Emit.EmitText;

/// <summary>
/// The Roslyn (C#) backend orchestrator: binds a program unit to a <see cref="BoundProgram"/> and renders it to
/// typed-native C# source, delegating to the decomposed emitters/renderers over a shared <see cref="EmissionContext"/>
/// (COBOLNET_DESIGN §17 §2.2): <see cref="FieldEmitter"/> (DATA DIVISION), <see cref="NumericRenderer"/> (arithmetic),
/// <see cref="ConditionRenderer"/> (conditions), and <see cref="OperandText"/> (DISPLAY images). It consumes only the
/// bound tree for the PROCEDURE DIVISION — it never walks the parse tree (that is the binder's job) — and an
/// unsupported construct surfaces as a bound error node and emits a LOUD <c>NotImplemented</c> guard (§1.4).
/// </summary>
/// <remarks><b>Status — G2:</b> groups→record structs, OCCURS→arrays, qualified/subscripted refs, figurative +
/// signed DISPLAY, level-88. Control flow is a sequential paragraph call-chain (the G4 PC dispatcher replaces it).</remarks>
public sealed class CSharpEmitter
{
    private EmissionContext _ctx = null!;
    private NumericRenderer _num = null!;
    private ConditionRenderer _cond = null!;

    /// <summary>Emit C# source for the first program unit in <paramref name="tree"/>.</summary>
    public string Emit(Core.CompilationUnitContext tree)
    {
        Core.ProgramUnitContext? program = tree.compilationGroup().SelectMany(g => g.programUnit()).FirstOrDefault();

        var data = new DataBinder();
        if (program is not null) data.Bind(program);
        var refs = new ReferenceResolver(data);
        BoundProgram bound = program is not null ? new StatementBinder(data, refs).Bind(program) : new BoundProgram([]);

        // Whole-group analysis (ISO §14.9 MOVE GR4): a numeric-DISPLAY leaf under a group used as a whole operand
        // must store its character image, because a whole-group move fills it without conversion (it may receive
        // spaces). Run AFTER binding (ReferenceResolver has recorded every whole-group reference) and BEFORE emit
        // (FieldEmitter / OperandText / NumericRenderer read the StoreAsImage flag).
        MarkStoreAsImage(data);

        var w = new CodeWriter();
        _ctx = new EmissionContext(w, data);
        _num = new NumericRenderer(_ctx);
        _cond = new ConditionRenderer(_num);

        w.Line("// <auto-generated>");
        w.Line("//   Generated by COBOL.NET — do not edit. A COBOL program compiled to typed-native C#.");
        w.Line("// </auto-generated>");
        w.Line("#nullable enable");
        w.Line("using CobolNet.Runtime;          // CobolNum / CobolString typed-native runtime substrates");
        w.Line();

        using (w.Block("internal static class Program"))
        {
            new FieldEmitter(_ctx).Emit();

            if (bound.Paragraphs.Count > 0)
                EmitDispatcher(bound, w);
            else
                using (w.Block("private static void Main()")) { }
        }

        return w.ToString();
    }

    /// <summary>
    /// Whole-group analysis (ISO/IEC 1989:2023 §14.9 MOVE GR4 / COBOLNET_DESIGN §14.4): for every group used as a
    /// whole operand, flag each numeric USAGE-DISPLAY descendant leaf to store its character image
    /// (<see cref="DataItem.StoreAsImage"/>). A whole-group move fills the group "without consideration for the
    /// individual elementary items", so such a leaf may receive non-numeric characters (e.g. spaces) that a native
    /// <c>long</c> cannot represent. A COMP/COMP-3/COMP-5/float leaf is left native (its group is then a genuine
    /// mixed-usage byte-island — Tier-C, deferred); numeric-edited / alphanumeric leaves are already string-stored.
    /// </summary>
    private static void MarkStoreAsImage(DataBinder data)
    {
        foreach (var group in data.WholeGroupReferenced)
            MarkNumericDisplayLeaves(group);

        static void MarkNumericDisplayLeaves(DataItem item)
        {
            foreach (var child in item.Children)
            {
                if (child.Occurs is not null) continue;   // OCCURS items aren't part of the no-OCCURS char-image model
                if (child.IsGroup) MarkNumericDisplayLeaves(child);
                else if (child.Pic is { Category: PicCategory.Numeric, IsFloat: false, Usage: Usage.Display })
                    child.StoreAsImage = true;
            }
        }
    }

    // ── The PC dispatcher (COBOLNET_DESIGN §5) ────────────────────────────────────────────────────────────

    private int _currentPc;     // the paragraph index being emitted (for EXIT PARAGRAPH / fall-through)
    private int _depCounter;    // unique-name counter for GO TO … DEPENDING selectors

    /// <summary>
    /// Emit the single program-counter dispatcher: each paragraph is a <c>case</c> in one <c>Dispatch</c> method;
    /// control is by pc value (GO TO sets pc; fall-through is pc+1; an out-of-line PERFORM is a recursive bounded
    /// <c>Dispatch(start, end)</c>). STOP RUN unwinds all frames via <c>StopRun</c>, caught at <c>Main</c>. This
    /// realizes the legacy's proven return-address / exit-bounded dispatch (DEVLOG 259–260) in idiomatic C#.
    /// </summary>
    private void EmitDispatcher(BoundProgram bound, CodeWriter w)
    {
        int n = bound.Paragraphs.Count;
        w.Line();
        // The dispatcher internals use a `__` prefix — COBOL data-names cannot contain a double underscore — so they
        // never collide with a program's fields (e.g. a COBOL `01 N` and the paragraph count `__N`).
        w.Line($"private const int __N = {n};   // paragraph count");
        w.Line();
        using (w.Block("private static void Main()"))
            w.Line("try { __Dispatch(0, -1); } catch (StopRun) { }");
        w.Line();
        using (w.Block("private static int __Dispatch(int __startPc, int __exitPc)"))
        {
            w.Line("int __pc = __startPc;");
            using (w.Block("while ((uint)__pc < (uint)__N)"))
            {
                w.Line("bool __atExit = __pc == __exitPc;   // captured before the body overwrites __pc");
                using (w.Block("switch (__pc)"))
                {
                    for (int i = 0; i < n; i++)
                    {
                        _currentPc = i;
                        using (w.Block($"case {i}:   // {bound.Paragraphs[i].CobolName}"))
                        {
                            if (!EmitStatementList(bound.Paragraphs[i].Statements))
                            {
                                w.Line($"__pc = {i + 1};");
                                w.Line("break;");
                            }
                        }
                    }
                    using (w.Block("default:")) { w.Line("__pc = __N;"); w.Line("break;"); }
                }
                w.Line("if (__atExit && __pc == __exitPc + 1) return __pc;   // a named THRU exit paragraph fell off its end");
            }
            w.Line("return __pc;");
        }
    }

    /// <summary>Emit a statement list (a paragraph case, an IF branch, or an inline-PERFORM body), suppressing dead
    /// code after an unconditional transfer; returns whether the list ends by transferring control out of the case.</summary>
    private bool EmitStatementList(IReadOnlyList<BoundStatement> stmts)
    {
        bool terminated = false;
        foreach (var st in stmts)
        {
            if (terminated) break;   // unreachable after an unconditional GO TO / STOP / EXIT PARAGRAPH
            terminated = EmitStatement(st);
        }
        return terminated;
    }

    /// <summary>Emit one statement; returns true if it unconditionally transfers control out of the paragraph case.</summary>
    private bool EmitStatement(BoundStatement s)
    {
        var w = _ctx.Writer;
        switch (s)
        {
            case BoundStop: w.Line("throw new StopRun();"); return true;
            case BoundGoTo g: w.Line($"__pc = {g.TargetPc};"); w.Line("break;"); return true;
            case BoundExitParagraph: w.Line($"__pc = {_currentPc + 1};"); w.Line("break;"); return true;
            case BoundExitPerform e: w.Line(e.Cycle ? "continue;" : "break;"); return false;   // inline-PERFORM loop
            case BoundGoToDepending d: EmitGoToDepending(d); return false;
            case BoundNop: return false;
            case BoundUnsupported u: w.Line(LoudStmt(u.Feature)); return false;
            case BoundDisplay d: EmitDisplay(d); return false;
            case BoundMove m: EmitMove(m); return false;
            case BoundAddTo a: EmitInPlace(a.Targets, "+", _num.Fold(a.Addends)); return false;
            case BoundAddGiving a: EmitGiving(a.Targets, _num.Fold(a.Addends)); return false;
            case BoundSubtractFrom a: EmitInPlace(a.Targets, "-", _num.Fold(a.Minuends)); return false;
            case BoundSubtractGiving a: EmitGiving(a.Targets, _num.Combine(_num.Render(a.From), "-", _num.Fold(a.Minuends))); return false;
            case BoundMultiplyBy a: EmitInPlace(a.Targets, "*", _num.Render(a.A)); return false;
            case BoundMultiplyGiving a: EmitGiving(a.Targets, _num.Combine(_num.Render(a.A), "*", _num.Render(a.B))); return false;
            case BoundDivideInto a: EmitDivide(a.Targets, null, _num.Render(a.Divisor)); return false;
            case BoundDivideGiving a: EmitDivide(a.Targets, _num.Render(a.Dividend), _num.Render(a.Divisor)); return false;
            case BoundCompute c: foreach (var t in c.Targets) { _ctx.TargetScale = ScaleOf(t); StoreArith(t, _num.Render(c.Rhs)); } return false;
            case BoundIf iff: EmitIf(iff); return false;
            case BoundInlinePerform p: EmitInlinePerform(p); return false;
            case BoundOutOfLinePerform p: EmitOutOfLinePerform(p); return false;
            case BoundSetConditions set: EmitSet(set); return false;
            default: w.Line(LoudStmt($"bound statement '{s.GetType().Name}'")); return false;
        }
    }

    /// <summary>Emit <c>GO TO … DEPENDING ON sel</c> (ISO §14.9.20 Format 2): a 1-based selector picks a pc; an
    /// out-of-range value transfers nowhere and falls through to the next statement.</summary>
    private void EmitGoToDepending(BoundGoToDepending d)
    {
        var w = _ctx.Writer;
        int id = _depCounter++;
        w.Line($"int __dep{id} = (int)({_num.AsNum(d.Selector).Expr});");
        using (w.Block($"switch (__dep{id})"))
            for (int k = 0; k < d.Targets.Count; k++)
                w.Line($"case {k + 1}: __pc = {d.Targets[k]}; break;");
        w.Line($"if (__dep{id} >= 1 && __dep{id} <= {d.Targets.Count}) break;   // in range → transfer (exit the dispatcher switch)");
    }

    private void EmitDisplay(BoundDisplay d)
    {
        var parts = d.Operands.Select(OperandText.AsString).ToList();
        string image = parts.Count == 0 ? "\"\"" : string.Join(" + ", parts);
        _ctx.Writer.Line(d.NoAdvancing ? $"System.Console.Write({image});" : $"System.Console.WriteLine({image});");
    }

    private void EmitMove(BoundMove m)
    {
        foreach (var target in m.Targets)
            if (target is RefModPlace)
                // A reference-modified receiver: the slice takes the source's characters (SpliceInto left-justifies,
                // space-fills, and truncates to the slice length), so pass the raw image, not a full-width store.
                _ctx.Writer.Line(target.Write(OperandText.AsString(m.Source)));
            else if (target.Item.IsGroup)
                EmitGroupMove(target, m.Source);
            else
                _ctx.Writer.Line(target.Write(ConvertSource(m.Source, target.Item)));
    }

    /// <summary>MOVE into a whole group (alphanumeric semantics, ISO §14.9 MOVE GR4 — no conversion, filled without
    /// consideration for subordinate items): the source's character image fills the group's leaves via
    /// <c>FromImage</c>. Handles any DISPLAY-homogeneous group — alphanumeric, numeric-edited, and numeric-DISPLAY
    /// leaves (the last stored as their character image, <see cref="DataItem.StoreAsImage"/>). A group with a
    /// COMP/COMP-3/COMP-5/float leaf is the genuine mixed-usage byte-island (Tier-C, deferred, loud).</summary>
    private void EmitGroupMove(Place target, BoundOperand source)
    {
        if (!target.Item.IsCharacterImage)
        {
            _ctx.Writer.Line(LoudStmt($"MOVE to mixed-usage group '{target.Item.CobolName}' with a COMP/binary leaf (Tier-C byte path, deferred)"));
            return;
        }
        int width = target.Item.ImageWidth;
        string image = source is BoundFigurative f
            ? $"new string({FigurativeFill(f.Kind)}, {width})"
            : $"CobolString.Store({OperandText.AsString(source)}, {width})";
        _ctx.Writer.Line($"{target.Read()}.FromImage({image});");
    }

    /// <summary>The C# expression a MOVE source converts to when stored into <paramref name="target"/>.</summary>
    private string ConvertSource(BoundOperand source, DataItem target)
    {
        var pic = target.Pic!;
        // A figurative constant fills the receiver to its width (ISO §8.3.1.2 / §14.9.24).
        if (source is BoundFigurative f && pic.Category is not PicCategory.Numeric)
            return $"new string({FigurativeFill(f.Kind)}, {pic.Length})";

        switch (pic.Category)
        {
            case PicCategory.Alphanumeric or PicCategory.NumericEdited:
                return $"CobolString.Store({OperandText.AsString(source)}, {pic.Length})";
            case PicCategory.Numeric:
                NumX n = _num.AsNum(source);
                string stored = $"CobolNum.Store({n.Expr}, {n.Scale}, {target.ProfileName})";
                // A whole-group-aliased numeric-DISPLAY receiver stores its character image, not the raw long.
                return target.StoreAsImage ? $"CobolNum.FormatDisplay({stored}, {target.ProfileName})" : stored;
            default:
                return "default";
        }
    }

    // ── Arithmetic ──────────────────────────────────────────────────────────────────────────────────────

    private void EmitInPlace(IReadOnlyList<Place> targets, string op, NumX value)
    {
        foreach (var t in targets) StoreArith(t, _num.Combine(NumericRenderer.FieldNum(t), op, value));
    }

    private void EmitGiving(IReadOnlyList<Place> targets, NumX value)
    {
        foreach (var t in targets) StoreArith(t, value);
    }

    private void EmitDivide(IReadOnlyList<Place> targets, NumX? dividend, NumX divisor)
    {
        foreach (var t in targets)
        {
            _ctx.TargetScale = ScaleOf(t);                   // the quotient is computed at the receiver's scale
            NumX num = dividend ?? NumericRenderer.FieldNum(t);   // DIVIDE … INTO with no GIVING divides the target itself
            StoreArith(t, _num.Combine(num, "/", divisor));
        }
    }

    /// <summary>Store an arithmetic result into a numeric target place via <c>CobolNum.Store</c>.</summary>
    private void StoreArith(Place target, NumX value)
    {
        if (target.Item.Pic is not { Category: PicCategory.Numeric, IsFloat: false })
        {
            _ctx.Writer.Line(LoudStmt($"arithmetic into a non-fixed-point target '{target.Item.CobolName ?? target.Read()}'"));
            return;
        }
        string stored = $"CobolNum.Store({value.Expr}, {value.Scale}, {target.Item.ProfileName})";
        // A whole-group-aliased numeric-DISPLAY receiver stores its character image, not the raw long.
        _ctx.Writer.Line(target.Write(target.Item.StoreAsImage ? $"CobolNum.FormatDisplay({stored}, {target.Item.ProfileName})" : stored));
    }

    private static int ScaleOf(Place p) => p.Item.Pic?.Scale ?? 0;

    // ── IF / PERFORM / SET ─────────────────────────────────────────────────────────────────────────────

    private void EmitIf(BoundIf iff)
    {
        var w = _ctx.Writer;
        using (w.Block($"if ({_cond.Render(iff.Condition)})"))
            EmitStatementList(iff.Then);
        if (iff.Else.Count > 0)
            using (w.Block("else"))
                EmitStatementList(iff.Else);
    }

    private void EmitInlinePerform(BoundInlinePerform p) => EmitPerform(p.Control, () => EmitStatementList(p.Body), inline: true);

    /// <summary>An out-of-line PERFORM is a recursive bounded <c>Dispatch(start, end)</c> over the target pc range
    /// (the C# call stack is the return-address stack, COBOLNET_DESIGN §5.4).</summary>
    private void EmitOutOfLinePerform(BoundOutOfLinePerform p) =>
        EmitPerform(p.Control, () => _ctx.Writer.Line($"__Dispatch({p.StartPc}, {p.EndPc});"), inline: false);

    private void EmitPerform(BoundPerformControl control, Action body, bool inline)
    {
        var w = _ctx.Writer;
        switch (control)
        {
            case PerformTimes t:
                using (w.Block($"for (long _i = 0; _i < {CountExpr(t.Count)}; _i++)")) body();
                break;
            case PerformUntil u when u.TestAfter:
                using (w.Block("do")) body();
                w.Line($"while (!({_cond.Render(u.Until)}));");
                break;
            case PerformUntil u:
                using (w.Block($"while (!({_cond.Render(u.Until)}))")) body();
                break;
            default:   // PerformOnce — an inline body runs once via do/while(false); an out-of-line call is unconditional
                if (inline) { using (w.Block("do")) body(); w.Line("while (false);"); }
                else body();
                break;
        }
    }

    private static string CountExpr(BoundOperand count) => count switch
    {
        BoundNumericLiteral n => n.Text,
        BoundFieldOperand f => f.Place.Read(),
        BoundOperandError e => LoudValue("long", e.Feature),
        _ => "1",
    };

    private void EmitSet(BoundSetConditions set)
    {
        foreach (var (parent, cond) in set.Sets)
        {
            var (low, _) = cond.Values[0];   // SET TO TRUE stores the first VALUE (ISO §14.9.39 Format 5)
            string rhs = parent.Item.Pic?.Category switch
            {
                PicCategory.Alphanumeric or PicCategory.NumericEdited =>
                    $"CobolString.Store({CsLiteral(DecodeCobolString(low))}, {parent.Item.Pic.Length})",
                PicCategory.Numeric =>
                    $"CobolNum.Store({UnscaledAtScale(low, parent.Item.Pic.Scale)}, {parent.Item.Pic.Scale}, {parent.Item.ProfileName})",
                _ => LoudValue("string", $"SET condition '{cond.Name}' over a group parent"),
            };
            _ctx.Writer.Line(parent.Write(rhs));
        }
    }
}
